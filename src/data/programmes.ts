/** Converts the directory into the shape the matching engine scores. */
export function getRealProgrammes(): Opportunity[] {
  return PROGRAMMES.map((p) => ({
    id: `real-${p.id}`,
    title: p.title,
    company: p.company,
    companyBlurb: p.blurb,
    location: p.location,
    type: p.type,
    tracks: p.tracks,
    skillsRequired: p.skills,
    degreeFields: p.degree ?? ["any"],
    eligibility: { note: STAGE_NOTE[p.stage] },
    experienceLevel: "none",
    sponsorshipStatus: p.sponsorship ?? "not_verified",
    companyType: p.companyType,
    sourceUrl: p.url,
    sourceName: `${p.company} careers`,
    verifiedAt: VERIFIED_ON,
    isDemo: false,
    skillsSource: "typical",
    stage: p.stage,
    visaNote: p.visaNote,
    visaSource: p.visaSource,
    verifiedNote: p.note,
    campusPages: p.campus,
  }));
}

