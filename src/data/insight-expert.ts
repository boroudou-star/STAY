/** Finds a concept named in the text (e.g. a daily "Explain X" question). */
export function conceptFor(text: string): ConceptKnowledge | undefined {
  const t = text.toLowerCase();
  return CONCEPTS.find((c) => t.includes(c.concept.toLowerCase()));
}

/** Concepts that belong to an area, using the area's keyConcepts list order. */
export function conceptsIn(names: string[]): ConceptKnowledge[] {
  return names.map((n) => CONCEPTS.find((c) => c.concept === n)).filter((c): c is ConceptKnowledge => Boolean(c));
}
